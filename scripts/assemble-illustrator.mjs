#!/usr/bin/env node

/**
 * Assembles dist/all2html.js from:
 * 1. JSON2 polyfill
 * 2. Core bundle (ES5 IIFE)
 * 3. ExtendScript exporter
 * All wrapped in a function main() { ... } main(); MRAP workaround.
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync, copyFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

const json2 = readFileSync(resolve(root, "plugins/illustrator/json2.js"), "utf-8");
const coreBundle = readFileSync(resolve(root, "dist/extendscript/all2html-core.js"), "utf-8");
const exporter = readFileSync(resolve(root, "plugins/illustrator/exporter.jsx"), "utf-8");

const assembled = `// all2html - generated ${new Date().toISOString().split("T")[0]}
// Do not edit this file directly. It is assembled from:
//   plugins/illustrator/json2.js (JSON polyfill)
//   dist/extendscript/all2html-core.js (core pipeline)
//   plugins/illustrator/exporter.jsx (Illustrator exporter)

function main() {

// === JSON polyfill ===
${json2}

// === Core pipeline (ES5 IIFE) ===
${coreBundle}

// === ExtendScript exporter ===
${exporter}

} // end main

main();
`;

mkdirSync(resolve(root, "dist"), { recursive: true });
const outPath = resolve(root, "dist/all2html.js");
writeFileSync(outPath, assembled, "utf-8");

const sizeKB = Math.round(assembled.length / 1024);
console.log(`Assembled: ${outPath} (${sizeKB}KB, ${assembled.split("\n").length} lines)`);

// Copy to panel dist if it exists so local panel builds/dev sessions can reuse it.
const panelDistJsx = resolve(root, "plugins/illustrator/panel/dist/cep/jsx");
if (existsSync(panelDistJsx)) {
  copyFileSync(outPath, resolve(panelDistJsx, "all2html.js"));
  console.log(`Copied to panel dist: ${panelDistJsx}/all2html.js`);
}
