#!/usr/bin/env node

import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { strToU8, zipSync } from "fflate";

const root = process.cwd();
const pluginDir = resolve(root, "plugins/after-effects");
const distDir = resolve(root, "dist/after-effects");
const packageJson = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8"));

function jsStringLiteral(value) {
  return JSON.stringify(value).replace(/\u2028/g, "\\u2028").replace(/\u2029/g, "\\u2029");
}

const exporter = readFileSync(resolve(pluginDir, "exporter.jsx"), "utf8");
const playerTemplate = readFileSync(resolve(pluginDir, "player-template.html"), "utf8");
const json2 = readFileSync(resolve(root, "plugins/illustrator/json2.js"), "utf8");
const readme = readFileSync(resolve(pluginDir, "README.md"), "utf8");

const assembled = `// all2html After Effects exporter - generated ${new Date().toISOString().split("T")[0]}
// Version: ${packageJson.version}
// Do not edit this file directly. It is assembled from:
//   plugins/after-effects/exporter.jsx
//   plugins/after-effects/player-template.html
//   plugins/illustrator/json2.js

(function () {
  $.global.__ALL2HTML_AE_JSON2__ = ${jsStringLiteral(json2)};
  $.global.__ALL2HTML_AE_PLAYER_TEMPLATE__ = ${jsStringLiteral(playerTemplate)};
})();

${exporter}
`;

rmSync(distDir, { recursive: true, force: true });
mkdirSync(distDir, { recursive: true });

writeFileSync(resolve(distDir, "all2html-ae.jsx"), assembled, "utf8");
writeFileSync(resolve(distDir, "README.md"), readme, "utf8");

const zipData = zipSync(
  {
    "all2html-after-effects/all2html-ae.jsx": strToU8(assembled),
    "all2html-after-effects/README.md": strToU8(readme)
  },
  { level: 9 }
);

const zipPath = resolve(root, "dist/all2html-after-effects.zip");
writeFileSync(zipPath, Buffer.from(zipData));

console.log(`Packaged After Effects exporter to ${zipPath}`);
console.log(`Wrote standalone script to ${resolve(distDir, "all2html-ae.jsx")}`);
